CREATE TABLE IF NOT EXISTS pending_registrations (
 id BIGSERIAL PRIMARY KEY, email VARCHAR(255) NOT NULL UNIQUE,
 user_name VARCHAR(255) NOT NULL UNIQUE, first_name VARCHAR(255) NOT NULL,
 last_name VARCHAR(255) NOT NULL, birth_date DATE NOT NULL, gender VARCHAR(255) NOT NULL,
 password_hash VARCHAR(255) NOT NULL, token VARCHAR(255) NOT NULL UNIQUE,
 code_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL, resend_at TIMESTAMP WITH TIME ZONE NOT NULL,
 attempts INTEGER NOT NULL DEFAULT 0, sends INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_pending_registration_created ON pending_registrations(created_at);
